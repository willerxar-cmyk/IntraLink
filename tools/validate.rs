//! Standalone native Rust validation runner. Run from the repository root.
//! Compile with rustc; no Cargo dependencies are required for the runner.
#![forbid(unsafe_code)]

use std::{env, fs, path::{Path, PathBuf}, process::{Command, ExitCode}};

#[derive(Default)]
struct Runner {
    passed: usize,
    failed: usize,
    blocked: usize,
}

impl Runner {
    fn run(&mut self, name: &str, program: &str, args: &[&str]) -> bool {
        println!("\n=== {name} ===\n$ {program} {}", args.join(" "));
        let passed = match Command::new(program).args(args).status() {
            Ok(status) => {
                println!("Exit: {status}");
                status.success()
            }
            Err(error) => {
                eprintln!("Could not run {program}: {error}");
                false
            }
        };
        if passed { self.passed += 1; } else { self.failed += 1; }
        passed
    }

    fn blocked(&mut self, name: &str, reason: &str) {
        eprintln!("BLOCKED: {name}: {reason}");
        self.blocked += 1;
    }

    fn feature(&mut self, feature: &str) {
        self.run("Feature Clippy", "cargo", &["clippy", "--locked", "-p", "intralink", "--features", feature, "--all-targets", "--", "-D", "warnings"]);
        self.run("Feature tests", "cargo", &["test", "--locked", "-p", "intralink", "--features", feature]);
        self.run("Feature release build", "cargo", &["build", "--locked", "-p", "intralink", "--features", feature, "--release"]);
    }
}

fn main() -> ExitCode {
    let mut resolve = false;
    let mut desktop = false;
    let mut vaapi = false;
    let mut resources = false;
    for arg in env::args().skip(1) {
        match arg.as_str() {
            "--resolve" => resolve = true,
            "--desktop" => desktop = true,
            "--vaapi" => vaapi = true,
            "--resources" => resources = true,
            "--help" | "-h" => {
                println!("Usage: validate [--resolve] [--desktop] [--vaapi] [--resources]\nRun from the IntraLink repository root. --resolve permits generating a missing Cargo.lock; existing lockfiles are never regenerated by this tool.");
                return ExitCode::SUCCESS;
            }
            _ => {
                eprintln!("Unknown argument: {arg}");
                return ExitCode::FAILURE;
            }
        }
    }
    if !Path::new("Cargo.toml").is_file() || !Path::new("crates/intralink-core/src/media_harness.rs").is_file() {
        eprintln!("Run from the IntraLink repository root");
        return ExitCode::FAILURE;
    }
    let mut runner = Runner::default();
    let rustc = runner.run("Rust compiler", "rustc", &["--version", "--verbose"]);
    let cargo = runner.run("Cargo", "cargo", &["--version"]);
    let dir = PathBuf::from("target/intralink-validation");
    if rustc {
        match fs::create_dir_all(&dir) {
            Ok(()) => {
                let binary = dir.join("core-tests.exe");
                // The fixed relative path is valid UTF-8 on every supported OS.
                let binary = binary.to_str().expect("ASCII path");
                if runner.run("Dependency-free core compile", "rustc", &["--edition=2024", "--test", "-D", "warnings", "crates/intralink-core/src/media_harness.rs", "-o", binary]) {
                    runner.run("Dependency-free core tests", binary, &[]);
                } else {
                    runner.blocked("Dependency-free core tests", "fresh compile failed; no stale binary executed");
                }
            }
            Err(error) => runner.blocked("Dependency-free core", &error.to_string()),
        }
    } else {
        runner.blocked("Dependency-free core", "rustc unavailable");
    }
    if cargo {
        runner.run("Formatting", "cargo", &["fmt", "--all", "--", "--check"]);
        let lock = Path::new("Cargo.lock");
        if !lock.exists() && resolve {
            runner.run("Initial dependency resolution (review and commit lockfile)", "cargo", &["generate-lockfile"]);
        }
        if lock.is_file() {
            runner.run("Locked dependency graph", "cargo", &["metadata", "--locked", "--format-version", "1"]);
            runner.run("Workspace Clippy", "cargo", &["clippy", "--locked", "--workspace", "--all-targets", "--", "-D", "warnings"]);
            runner.run("Workspace tests", "cargo", &["test", "--locked", "--workspace"]);
            runner.run("Workspace release build", "cargo", &["build", "--locked", "--workspace", "--release"]);
            if resources { runner.feature("resource-monitor"); }
            if desktop {
                if cfg!(any(target_os = "windows", target_os = "linux")) { runner.feature("desktop-preview"); }
                else { runner.blocked("Desktop preview", "only Windows and Linux supported"); }
            }
            if vaapi {
                if cfg!(target_os = "linux") { runner.feature("vaapi-probe"); }
                else { runner.blocked("VA-API probe", "Linux only"); }
            }
            // Test the selected features together, not only in isolation.
            let mut combined = Vec::new();
            if resources { combined.push("resource-monitor"); }
            if desktop && cfg!(any(target_os = "windows", target_os = "linux")) {
                combined.push("desktop-preview");
            }
            if vaapi && cfg!(target_os = "linux") { combined.push("vaapi-probe"); }
            if combined.len() > 1 {
                runner.feature(&combined.join(","));
            }
        } else {
            runner.blocked("Locked Cargo gates", "missing Cargo.lock; rerun with --resolve to generate a reviewable initial lockfile");
        }
    } else {
        runner.blocked("Cargo gates", "cargo unavailable");
    }
    println!("\nValidation: {} passed; {} failed; {} blocked. Native session/GPU testing is separate.", runner.passed, runner.failed, runner.blocked);
    if runner.failed == 0 && runner.blocked == 0 { ExitCode::SUCCESS } else { ExitCode::FAILURE }
}
